-- 1. STORE OWNERS
CREATE TABLE IF NOT EXISTS public.owner_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    owner_name TEXT NOT NULL,
    business_name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    gst_number TEXT DEFAULT 'Unregistered',
    address TEXT DEFAULT '',
    mobile TEXT DEFAULT '',
    website TEXT DEFAULT '',
    upi TEXT DEFAULT '',
    bank_account TEXT DEFAULT '',
    ifsc TEXT DEFAULT '',
    is_verified BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. CUSTOMER PROFILES
CREATE TABLE IF NOT EXISTS public.customer_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE CASCADE,
    customer_name TEXT NOT NULL,
    mobile TEXT UNIQUE NOT NULL,
    email TEXT UNIQUE,
    address TEXT DEFAULT '',
    is_verified BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. PRODUCTS (Scoped to owner_id; Customers see all products across all owners)
CREATE TABLE IF NOT EXISTS public.products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT REFERENCES public.owner_profile(id) ON DELETE CASCADE,
    product_name TEXT NOT NULL,
    description TEXT DEFAULT '',
    company TEXT DEFAULT '',
    category TEXT DEFAULT 'General',
    barcode TEXT DEFAULT '',
    purchase_price NUMERIC(10, 2) DEFAULT 0,
    selling_price NUMERIC(10, 2) NOT NULL,
    quantity INTEGER NOT NULL DEFAULT 0,
    gst NUMERIC(5, 2) NOT NULL DEFAULT 0,
    image TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. STORE CUSTOMERS CRM (Scoped to owner_id so owner sees customers who ordered from them)
CREATE TABLE IF NOT EXISTS public.customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT REFERENCES public.owner_profile(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    mobile TEXT NOT NULL,
    address TEXT DEFAULT '',
    total_purchases NUMERIC(12, 2) DEFAULT 0,
    total_orders INTEGER DEFAULT 0,
    last_visited TEXT DEFAULT '',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. EMPLOYEES / STAFF (Scoped to owner_id)
CREATE TABLE IF NOT EXISTS public.employees (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT REFERENCES public.owner_profile(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'Staff',
    mobile TEXT NOT NULL,
    salary NUMERIC(10, 2) NOT NULL DEFAULT 0,
    status TEXT NOT NULL DEFAULT 'Active',
    join_date TEXT NOT NULL DEFAULT CURRENT_DATE::text,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. POS INVOICES / BILLS (Scoped to owner_id)
CREATE TABLE IF NOT EXISTS public.bills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id BIGINT REFERENCES public.owner_profile(id) ON DELETE CASCADE,
    invoice_number TEXT NOT NULL,
    customer_name TEXT NOT NULL,
    customer_mobile TEXT DEFAULT '',
    customer_address TEXT DEFAULT '',
    date TEXT NOT NULL,
    time TEXT NOT NULL,
    sub_total NUMERIC(12, 2) NOT NULL,
    gst_amount NUMERIC(12, 2) NOT NULL,
    grand_total NUMERIC(12, 2) NOT NULL,
    payment_mode TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 7. POS BILL ITEMS
CREATE TABLE IF NOT EXISTS public.bill_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id BIGINT REFERENCES public.bills(id) ON DELETE CASCADE,
    product_id BIGINT,
    product_name TEXT NOT NULL,
    quantity INTEGER NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    gst_percent NUMERIC(5, 2) NOT NULL,
    total NUMERIC(12, 2) NOT NULL
);

-- 8. CUSTOMER ONLINE ORDERS
CREATE TABLE IF NOT EXISTS public.orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number TEXT UNIQUE NOT NULL,
    owner_id BIGINT REFERENCES public.owner_profile(id),
    customer_name TEXT NOT NULL,
    customer_mobile TEXT NOT NULL,
    customer_address TEXT NOT NULL,
    product_id BIGINT,
    product_name TEXT NOT NULL,
    product_image TEXT DEFAULT '',
    quantity INTEGER NOT NULL DEFAULT 1,
    total_amount NUMERIC(12, 2) NOT NULL,
    gst_amount NUMERIC(12, 2) NOT NULL,
    final_amount NUMERIC(12, 2) NOT NULL,
    payment_method TEXT NOT NULL DEFAULT 'UPI',
    payment_status TEXT NOT NULL DEFAULT 'Paid',
    order_date TEXT NOT NULL,
    order_time TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- INDEXES FOR PERFORMANCE
CREATE INDEX IF NOT EXISTS idx_products_owner_id ON public.products(owner_id);
CREATE INDEX IF NOT EXISTS idx_customers_owner_id ON public.customers(owner_id);
CREATE INDEX IF NOT EXISTS idx_employees_owner_id ON public.employees(owner_id);
CREATE INDEX IF NOT EXISTS idx_bills_owner_id ON public.bills(owner_id);
CREATE INDEX IF NOT EXISTS idx_orders_owner_id ON public.orders(owner_id);
CREATE INDEX IF NOT EXISTS idx_bill_items_bill_id ON public.bill_items(bill_id);

-- ENABLE ROW LEVEL SECURITY (RLS)
ALTER TABLE public.owner_profile ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.customer_profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.customers ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.employees ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bills ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.bill_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;

-- PERMISSIVE RLS POLICIES (Allows seamless web app read/write access with Supabase anon key)
DO $$
BEGIN
    DROP POLICY IF EXISTS "Public access owner_profile" ON public.owner_profile;
    CREATE POLICY "Public access owner_profile" ON public.owner_profile FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Public access customer_profiles" ON public.customer_profiles;
    CREATE POLICY "Public access customer_profiles" ON public.customer_profiles FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Public access products" ON public.products;
    CREATE POLICY "Public access products" ON public.products FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Public access customers" ON public.customers;
    CREATE POLICY "Public access customers" ON public.customers FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Public access employees" ON public.employees;
    CREATE POLICY "Public access employees" ON public.employees FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Public access bills" ON public.bills;
    CREATE POLICY "Public access bills" ON public.bills FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Public access bill_items" ON public.bill_items;
    CREATE POLICY "Public access bill_items" ON public.bill_items FOR ALL USING (true) WITH CHECK (true);

    DROP POLICY IF EXISTS "Public access orders" ON public.orders;
    CREATE POLICY "Public access orders" ON public.orders FOR ALL USING (true) WITH CHECK (true);
END $$;
